#!/usr/bin/env python3
"""Copy the shared docs each skill reads into that skill's references/ folder.

A skill installed on its own (`npx skills add withqwerty/nutmeg`, or any agent
that reads the Agent Skills format) gets only its own folder: not docs/, not
skills/_shared/ and not another skill's references/. So each skill refers to
shared docs as `references/<name>.md`, relative to its own folder, and this
script keeps a copy of each one there. The copies start with a "Generated"
line; edit the source, never the copy.

    python3 scripts/sync_skill_refs.py           # write the copies
    python3 scripts/sync_skill_refs.py --check   # exit 1 if a copy is missing, stale or unused

The plugin's agents and hooks keep `${CLAUDE_PLUGIN_ROOT}/...` paths: they
exist only in the Claude Code plugin, where the whole repository is installed.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"

# Shared docs a skill may read, by file name.
SOURCES = {
    "accuracy-guardrail.md": "docs/accuracy-guardrail.md",
    "entity-resolution-routing.md": "docs/entity-resolution-routing.md",
    "glossary.md": "docs/glossary.md",
    "metric-misuse.md": "docs/metric-misuse.md",
    "provenance-contract.md": "docs/provenance-contract.md",
    "understanding.md": "docs/understanding.md",
    "campos-bridge.md": "skills/_shared/campos-bridge.md",
    "chart-canon.md": "skills/brainstorm/references/chart-canon.md",
    "viz-styles.md": "skills/brainstorm/references/viz-styles.md",
}

MARKER = "<!-- Generated by scripts/sync_skill_refs.py"
REF = re.compile(r"references/([a-z0-9-]+\.md)")
PLUGIN_PATH = re.compile(r"\$\{CLAUDE_PLUGIN_ROOT\}/(?:docs|skills/_shared|skills/brainstorm/references)/([a-z0-9-]+\.md)")


def header(source):
    return f"{MARKER} from {source}. Edit that file, then run the script. -->\n\n"


def skill_relative(text):
    """Point plugin-root paths to shared docs at the copy in the skill's references/ folder."""
    return PLUGIN_PATH.sub(lambda m: f"references/{m.group(1)}" if m.group(1) in SOURCES else m.group(0), text)


def is_generated(path):
    return path.read_text(encoding="utf-8").startswith(MARKER)


def wanted(skill):
    """{copy path: text} for every shared doc the skill reads, directly or through another shared doc."""
    own = [skill / "SKILL.md"] + [p for p in sorted((skill / "references").glob("*.md")) if not is_generated(p)]
    texts = [p.read_text(encoding="utf-8") for p in own]
    native = {p.name for p in own}
    out, seen = {}, set()
    while texts:
        for name in REF.findall(texts.pop()):
            if name in seen or name in native or name not in SOURCES:
                continue
            seen.add(name)
            text = skill_relative((ROOT / SOURCES[name]).read_text(encoding="utf-8"))
            out[skill / "references" / name] = header(SOURCES[name]) + text
            texts.append(text)
    return out


def main(argv):
    check = "--check" in argv
    problems, errors = [], []
    for skill in sorted(p.parent for p in SKILLS.glob("*/SKILL.md")):
        files = wanted(skill)
        for path, text in files.items():
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                problems.append(f"{path.relative_to(ROOT)} is {'stale' if path.exists() else 'missing'}")
                if not check:
                    path.parent.mkdir(exist_ok=True)
                    path.write_text(text, encoding="utf-8")
        for path in sorted((skill / "references").glob("*.md")):
            if path not in files and is_generated(path):
                problems.append(f"{path.relative_to(ROOT)} is no longer used")
                if not check:
                    path.unlink()
        for path in [skill / "SKILL.md"] + sorted((skill / "references").glob("*.md")):
            if PLUGIN_PATH.search(path.read_text(encoding="utf-8")):
                errors.append(f"{path.relative_to(ROOT)} refers to a shared doc by its plugin path; "
                              "write references/<name>.md instead")
    for error in errors:
        print(f"error: {error}")
    if check:
        if problems:
            print("Skill references are out of date (run python3 scripts/sync_skill_refs.py):")
            print("\n".join(f"- {p}" for p in problems))
        elif not errors:
            print("Skill references are up to date.")
        return 1 if problems or errors else 0
    print("\n".join(f"updated: {p}" for p in problems) or "Skill references are up to date.")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
